			<h1 class="mt-3 text-brand-text">Editorial policy</h1>
			<p class="mt-5 text-lg leading-8 text-brand-muted">Love Long Eaton is an independent local guide maintained by Midas Web. This page explains how we decide what to publish and how we try to keep it useful and accurate.</p>

			<div class="mt-10 space-y-9 text-base leading-8 text-brand-muted">
				<section>
					<h2 class="text-2xl text-brand-text">What we publish</h2>
					<p class="mt-3">We cover events, activities, businesses, public places and practical updates with a clear connection to Long Eaton and nearby communities. We favour details that help a reader make a decision or plan a visit, rather than publishing listings simply to increase the number of pages on the site.</p>
				</section>
				<section>
					<h2 class="text-2xl text-brand-text">Sources and verification</h2>
					<p class="mt-3">We check information against first-party sources where possible, including an organiser’s website or booking page, a venue, a business’s official channels, and local-authority notices. Source links are included on listings and updates when available. We do not treat an unverified social post as confirmation of a date, price or venue.</p>
				</section>
				<section>
					<h2 class="text-2xl text-brand-text">Originality and attribution</h2>
					<p class="mt-3">Our guides are assembled and written for this site around practical local questions. When a news update depends on another organisation’s announcement, we identify and link to that source. Images supplied by a venue, organiser or business are used to illustrate the relevant listing and are not presented as our own photography.</p>
				</section>
				<section>
					<h2 class="text-2xl text-brand-text">Updates and corrections</h2>
					<p class="mt-3">Time-sensitive pages tell readers to confirm details with the organiser because schedules can change quickly. We remove expired events from current listings and review reported errors against a reliable source. To request a correction, use the contact form and include the page address, the detail that is wrong and a source for the replacement information.</p>
				</section>
				<section>
					<h2 class="text-2xl text-brand-text">Commercial independence</h2>
					<p class="mt-3">A listing does not imply endorsement. Suggestions from businesses and organisers are assessed using the same local relevance and usefulness criteria as other additions. Advertising does not determine editorial coverage. If we introduce paid or sponsored content, it will be labelled clearly.</p>
